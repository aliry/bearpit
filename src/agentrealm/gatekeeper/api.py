    @app.get("/api/runs")
    async def list_runs(scenario: str | None = None, limit: int = 300) -> dict[str, Any]:
        """Every past + live run with its state, outcome, spend and last-activity time — the
        history view. Scenario is derived from the realm id (auto ids carry a -hex6 suffix)."""
        chron = get_chron()
        active = set(get_manager().active())
        runs: list[dict[str, Any]] = []
        for rid in await chron.realms():
            events = await chron.events(rid)
            if not events:
                continue
            lifecycle = [e for e in events if e.kind == EventKind.LIFECYCLE]
            state = lifecycle[-1].payload.get("event") if lifecycle else "unknown"
            outcome, spend = None, 0.0
            for e in events:
                if e.kind == EventKind.VERDICT:
                    outcome = e.payload.get("outcome", outcome)
                elif e.kind == EventKind.SPEND:
                    spend += float(e.payload.get("usd", 0))
            is_active = rid in active
            if not is_active and state in NON_TERMINAL:
                state = "interrupted"
            runs.append({
                "realm_id": rid, "scenario": re.sub(r"-[0-9a-f]{6}$", "", rid),
                "state": state, "outcome": outcome, "spend": round(spend, 4),
                "updated": max(e.ts_ms for e in events), "active": is_active,
            })
        if scenario:
            runs = [r for r in runs if r["scenario"] == scenario]
        runs.sort(key=lambda r: r["updated"], reverse=True)
        return {"runs": runs[:limit], "capacity": get_manager().max_active, "active": len(active)}

