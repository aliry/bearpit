    # --- Scribe: guided scenario authoring (#66, #73, #75) ---------------------
    # One session per wizard/edit conversation, created by POST /api/scribe/session (ids are
    # server-generated). Conversations PERSIST per scenario (spec §19): edit sessions bind on
    # open and resume the stored history; create sessions bind at approve. Live edit sessions
    # are also keyed by scenario, so revisiting an assist page resumes the SAME session instead
    # of minting an orphan. In UI mode the model NEVER writes: create-mode drafts land via
    # /api/scribe/approve, edit-mode drafts via the editor's PUT — both deterministic, no model
    # call. Scribe uses the SAME user scenarios dir the dashboard launches from, so an approved
    # scenario appears in the Scenarios list at once.
    @dataclass
    class _ScribeConn:
        session: ScribeSession
        mode: str  # "create" | "edit"
        store: PackageStore

    _scribe: dict[str, _ScribeConn] = {}
    _scribe_edit: dict[str, str] = {}  # scenario -> live edit session id (for session reuse)

    _CREATE_OPENING = (
        "Give me a short description of the scenario you want to build — what happens, "
        "who's in it, and how it ends."
    )

    def _scribe_data_root() -> Path:
        return scribe_root or Path.home() / ".agentrealm" / "scribe"

    def _new_scribe_loop(mode: str) -> tuple[ScribeLoop, PackageStore]:
        base_url = os.environ.get("SCRIBE_API_BASE", "http://127.0.0.1:4000/v1")
        api_key = os.environ.get("SCRIBE_API_KEY", "")
        store: PackageStore = scribe_store or ApiPackageStore(
            user_dir=_import_base(), example_dirs=[_scenario_bases()[1]]
        )
        loop = build_scribe(
            base_url, _scribe_data_root(), backend=scribe_backend, store=store,
            api_key=api_key, model=os.environ.get("SCRIBE_MODEL") or DEFAULT_MODEL,
            mode=mode
        )
        return loop, store

    @app.post("/api/scribe/session")
    async def scribe_session_create(req: ScribeSessionCreate) -> dict[str, Any]:
        """Open a guided authoring session. Deterministic — NO model call: the opening question
        is canned, and edit mode just loads the scenario for context + the preview pane. An edit
        request for a scenario with a live session returns THAT session (with its visible
        history) rather than minting a new one; otherwise the stored history is resumed."""
        sid = "s-" + secrets.token_hex(8)
        if req.mode == "create":
            loop, store = _new_scribe_loop("guided-create")
            session = ScribeSession(loop, history_store=HistoryStore(_scribe_data_root()))
            _scribe[sid] = _ScribeConn(session, "create", store)
            return {
                "session_id": sid,
                "opening": {"kind": "question", "text": _CREATE_OPENING, "options": []},
            }
        if req.mode == "edit":
            name = req.scenario or ""
            opening = {
                "kind": "question",
                "text": f"What would you like to change about {name!r}?",
                "options": [],
            }

            async def _manifest(store: PackageStore) -> dict[str, Any]:
                try:
                    project = await store.read(name)
                except (FileNotFoundError, KeyError, PackageError) as exc:
                    raise HTTPException(status_code=404, detail=f"no scenario {name!r}") from exc
                return project.model_dump(mode="json", by_alias=True, exclude_none=True)

            live_sid = _scribe_edit.get(name)
            live = _scribe.get(live_sid) if live_sid else None
            if live is not None and live_sid is not None:  # resume the live session as-is
                return {
                    "session_id": live_sid,
                    "opening": opening,
                    "package": await _manifest(live.store),
                    "history": visible_history(live.session.history),
                }
            loop, store = _new_scribe_loop("guided-edit")
            manifest = await _manifest(store)
            note = f"Current scenario {name!r}:\n{json.dumps(manifest, indent=2)}"
            session = await ScribeSession.resume(
                loop,
                scenario=name,
                history_store=HistoryStore(_scribe_data_root()),
                context_note=note,
            )
            _scribe[sid] = _ScribeConn(session, "edit", store)
            _scribe_edit[name] = sid
            return {
                "session_id": sid,
                "opening": opening,
                "package": manifest,
                "history": visible_history(session.history),
            }
        raise HTTPException(status_code=400, detail="mode must be 'create' or 'edit'")

    @app.post("/api/scribe/message")
    async def scribe_message(req: ScribeMessage) -> StreamingResponse:
        """Stream one Scribe turn as newline-delimited JSON LoopEvents (kind/text/name) so the
        wizard can show tool activity, questions, drafts, and the final reply live."""
        conn = _scribe.get(req.session_id)
        if conn is None:
            raise HTTPException(status_code=404, detail="unknown session — open one first")
        session = conn.session

        async def gen() -> AsyncIterator[bytes]:
            try:
                async for ev in session.send(req.text):
                    line = json.dumps({"kind": ev.kind, "text": ev.text, "name": ev.name})
                    yield (line + "\n").encode()
            except Exception as exc:  # surface a failed turn instead of a dead stream
                logging.exception("scribe turn failed")
                yield (json.dumps({"kind": "error", "text": str(exc)}) + "\n").encode()

        return StreamingResponse(gen(), media_type="application/x-ndjson")

    @app.post("/api/scribe/approve")
    async def scribe_approve(req: ScribeApprove) -> dict[str, Any]:
        """Write a create-session's stashed draft. Deterministic — NO model call. Edit sessions
        save through the editor's PUT instead."""
        conn = _scribe.get(req.session_id)
        if conn is None:
            raise HTTPException(status_code=404, detail="unknown session")
        if conn.mode != "create":
            raise HTTPException(
                status_code=409,
                detail="approve applies to create sessions; edit sessions save via "
                "PUT /api/packages/{name}",
            )
        draft = conn.session.draft
        if draft is None:
            raise HTTPException(status_code=409, detail="no draft to approve yet")
        try:  # belt-and-braces: the draft was validated at propose time; re-check before writing
            project = Project.model_validate(draft)
        except ValidationError as exc:
            raise HTTPException(
                status_code=400, detail=f"draft no longer validates: {exc}"
            ) from exc
        result = scribe_validate(project)
        if not result.ok:
            raise HTTPException(
                status_code=400, detail="draft no longer validates: " + "; ".join(result.errors)
            )
        name = sc._slug(project.metadata.name)
        if not name:
            raise HTTPException(status_code=400, detail="draft has no usable metadata.name")
        if await conn.store.has_user(name):
            raise HTTPException(
                status_code=409,
                detail=f"a scenario named {name!r} already exists — ask the assistant for a "
                "different name, or edit the existing one",
            )
        versions = Versions(_scribe_data_root() / "versions")
        await versions.snapshot(name, None)  # pre-create snapshot, same as the CLI write path
        await conn.store.write(name, project)
        # the wizard conversation attaches to the new scenario (§19) — a later "Edit with
        # assistant" resumes the authoring context
        await conn.session.bind(name)
        return {"name": name}

    @app.delete("/api/scribe/history/{scenario}")
    async def scribe_history_delete(scenario: str) -> dict[str, Any]:
        """Start fresh (§19): delete the stored history AND drop any live session bound to the
        scenario. 404 when the scenario has neither."""
        hstore = HistoryStore(_scribe_data_root())
        try:
            had_file = await hstore.has(scenario)
        except ValueError as exc:
            raise HTTPException(status_code=404, detail=str(exc)) from exc
        live = [s for s, c in _scribe.items() if c.session.scenario == scenario]
        if not had_file and not live:
            raise HTTPException(status_code=404, detail=f"no history for {scenario!r}")
        for s in live:
            _scribe.pop(s, None)
        _scribe_edit.pop(scenario, None)
        await hstore.delete(scenario)
        return {"deleted": scenario}

    @app.post("/api/scribe/history/{scenario}/summarize")
    async def scribe_history_summarize(scenario: str) -> dict[str, Any]:
        """Summarize now (§19): collapse the whole thread to the LLM summary immediately —
        the live session's history when one exists, else the stored file — save, and return
        the new visible thread. 404 when the scenario has neither."""
        hstore = HistoryStore(_scribe_data_root())
        live = next(
            (c for c in _scribe.values() if c.session.scenario == scenario), None
        )
        if live is not None:
            await live.session.compact_now()
            return {"history": visible_history(live.session.history)}
        try:
            had_file = await hstore.has(scenario)
        except ValueError as exc:
            raise HTTPException(status_code=404, detail=str(exc)) from exc
        if not had_file:
            raise HTTPException(status_code=404, detail=f"no history for {scenario!r}")
        loop, _ = _new_scribe_loop("guided-edit")
        history = await hstore.load(scenario)
        history = await compact(history, loop.backend, loop.model, keep_tail=0)
        await hstore.save(scenario, history)
        return {"history": visible_history(history)}

