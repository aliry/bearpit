def _import_base() -> Path:
    """Where uploaded scenario folders are stored (persists across restarts)."""
    return Path(
        os.environ.get("AGENTREALM_SCENARIOS_DIR", str(Path.home() / ".agentrealm" / "scenarios"))
    )


def _scenario_bases() -> list[Path]:
    """Dirs scanned for scenario packages, in precedence order: the writable user dir first (so
    edits shadow a bundled template of the same name), then the read-only examples."""
    return [_import_base(), Path(os.environ.get("AGENTREALM_EXAMPLES_DIR", "examples"))]


def _find_scenario(name: str) -> Path | None:
    for base in _scenario_bases():
        path = base / name
        if (path / "project.json").exists():
            return path
    return None


