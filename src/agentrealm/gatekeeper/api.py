    @app.get("/api/packages")
    async def list_packages() -> dict[str, Any]:
        """Scenario packages available to run — user scenarios + bundled examples (folders with a
        project.json). A user scenario shadows a bundled example of the same name. Each entry
        carries light metadata (read from project.json, no full validation) for the card list."""
        user_dir = str(_import_base())
        seen: dict[str, dict[str, Any]] = {}
        for base in _scenario_bases():
            if not base.is_dir():
                continue
            for d in sorted(base.iterdir()):
                if not (d / "project.json").exists() or d.name in seen:
                    continue
                meta: dict[str, Any] = {}
                try:
                    meta = json.loads((d / "project.json").read_text()).get("metadata", {}) or {}
                except (OSError, json.JSONDecodeError):
                    meta = {}
                agents_dir = d / "agents"
                n_agents = sum(
                    1 for a in agents_dir.iterdir() if (a / "agent.json").exists()
                ) if agents_dir.is_dir() else 0
                seen[d.name] = {
                    "name": d.name, "path": str(d),
                    "title": meta.get("name") or d.name,
                    "description": meta.get("description") or "",
                    "tags": meta.get("tags") or [],
                    "category": meta.get("category") or "",
                    "agents": n_agents,
                    "editable": str(base) == user_dir,  # user scenarios can be edited/deleted
                }
        return {"packages": sorted(seen.values(), key=lambda p: p["name"])}

    @app.get("/api/packages/{name}")
    async def package_detail(name: str) -> dict[str, Any]:
        """Full details of one scenario for the preview page (config + roster)."""
        if "/" in name or ".." in name:
            raise HTTPException(status_code=400, detail="invalid scenario name")
        path = _find_scenario(name)
        if path is None:
            raise HTTPException(status_code=404, detail=f"no scenario {name!r}")
        try:
            project = load_package(str(path))
        except PackageError as exc:
            raise HTTPException(status_code=400, detail=str(exc)) from exc
        return serialize_project(project, name, str(path))

    @app.post("/api/packages/import")
    async def import_scenario(files: list[UploadFile] = File(...)) -> dict[str, Any]:
        """Import a scenario project FOLDER (uploaded via a directory picker) into the scenario
        list. Reconstructs the folder, validates it, and stores it under the imports dir."""
        import re
        import shutil

        if not files or len(files) > 500:
            raise HTTPException(status_code=400, detail="select one scenario folder")
        roots = {(f.filename or "").split("/")[0] for f in files if "/" in (f.filename or "")}
        if len(roots) != 1:
            raise HTTPException(status_code=400, detail="select a single scenario folder")
        root = roots.pop()
        name = re.sub(r"[^a-z0-9-]+", "-", root.lower()).strip("-")
        if not name:
            raise HTTPException(status_code=400, detail="invalid folder name")

        dest = _import_base() / name
        if dest.exists():
            shutil.rmtree(dest)
        dest.mkdir(parents=True, exist_ok=True)
        total = 0
        try:
            for f in files:
                parts = [p for p in (f.filename or "").split("/") if p and p not in (".", "..")]
                if len(parts) < 2 or parts[0] != root:
                    continue  # skip anything outside the selected folder
                data = await f.read()
                total += len(data)
                if total > 5_000_000:
                    raise HTTPException(status_code=413, detail="scenario folder too large (>5MB)")
                target = dest.joinpath(*parts[1:])
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
            project = load_package(str(dest))
        except HTTPException:
            shutil.rmtree(dest, ignore_errors=True)
            raise
        except Exception as exc:
            shutil.rmtree(dest, ignore_errors=True)
            raise HTTPException(status_code=400, detail=f"not a valid scenario: {exc}") from exc
        return {"name": name, "title": project.metadata.name, "agents": len(project.agents)}

