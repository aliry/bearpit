async def reconcile_orphans(chron: Chronicle) -> int:
    """On startup, no realm can still be running (the manager starts empty). Any realm whose last
    lifecycle event is non-terminal was cut off by a restart — record an 'interrupted' event so
    its state is honest. Returns how many were reconciled."""
    n = 0
    for realm_id in await chron.realms():
        lifecycle = await chron.events(realm_id, kind=EventKind.LIFECYCLE)
        if lifecycle and lifecycle[-1].payload.get("event") in NON_TERMINAL:
            await chron.append_event(
                realm_id, EventKind.LIFECYCLE, {"event": "interrupted", "detail": "server restart"}
            )
            n += 1
    return n


def _skill_content(source: str, ref: str, pkg_path: str) -> str:
    """The SKILL.md text for a skill ref, so the UI can show it: built-ins from the library,
    local skills read from the package. External (github) skills aren't resolvable here."""
    if source == "builtin":
        from agentrealm.forge.skills import BUILTIN_SKILLS
        return BUILTIN_SKILLS.get(ref, "")
    if source == "local":
        import pathlib
        try:
            return (pathlib.Path(pkg_path) / "skills" / ref / "SKILL.md").read_text()
        except OSError:
            return ""
    return ""


def serialize_project(project: Any, name: str, path: str) -> dict[str, Any]:
    """A display-friendly view of a scenario: config + roster, for the preview page."""
    md, spec, env = project.metadata, project.spec, project.spec.environment
    ref = project.referee
    skill_contents: dict[str, str] = {}  # "source:ref" -> SKILL.md text (deduped across agents)
    for a in project.agents:
        for sk in a.skills:
            key = f"{sk.source}:{sk.ref}"
            if key not in skill_contents:
                content = _skill_content(str(sk.source), sk.ref, path)
                if content:
                    skill_contents[key] = content
    # roster in display order (referee first), and each agent's resolved message color
    roster = sorted(project.agents, key=lambda a: 0 if ref and a.id == ref.id else 1)
    colors = resolve_agent_colors(roster)
    return {
        "name": name, "path": path, "title": md.name, "description": md.description or "",
        "tags": list(md.tags or []), "author": md.author or "", "category": md.category or "",
        "goals": list(spec.goals or []), "guidelines": spec.guidelines or "",
        "restrictions": spec.restrictions or "",
        "environment": {
            "network_egress": str(env.network_egress),
            "shared_folder": bool(env.shared_folder.enabled),
            "require_mention": bool(env.require_mention),
            "allow_side_channels": bool(env.allow_side_channels),
            "egress_allowlist": list(env.egress_allowlist or []),
        },
        "referee_opens": bool(spec.referee_opens),
        "provide_tools": bool(spec.provide_tools),
        "stall_nudge": bool(spec.stall_nudge),
        "mechanics": [m.model_dump(mode="json") for m in spec.mechanics],
        "turns": spec.turns.model_dump(mode="json") if spec.turns is not None else None,
        "termination": [
            {k: v for k, v in t.model_dump(mode="json").items() if v is not None}
            for t in spec.termination
        ],
        "referee": ref.id if ref else None,
        # referee first (stable otherwise) — the host/adjudicator heads the roster in the UI
        "agents": [
            {
                "id": a.id, "name": a.name or a.id, "role": str(a.role),
                "color": colors[a.id],
                "persona": a.persona or "", "goals": list(a.goals or []),
                "responsibilities": list(a.responsibilities or []), "rubric": a.rubric or "",
                # the capability tier the agent asks for; the active provider resolves it at launch
                "model_category": str(a.model_category),
                "model": str(a.model_category),
                "budget": a.budget.max_usd,
                # an optional exact-model override (null for category-based agents) — round-trips
                "model_ref": a.model.model_dump(mode="json") if a.model else None,
                "budget_ref": a.budget.model_dump(mode="json"),
                "private_messaging": a.private_messaging.model_dump(mode="json"),
                "skills": [f"{sk.source}:{sk.ref}" for sk in a.skills],
            }
            for a in roster
        ],
        "skill_contents": skill_contents,
    }


async def realm_status(chron: Chronicle, realm_id: str) -> dict[str, Any]:
    events = await chron.events(realm_id)
    if not events:
        raise HTTPException(status_code=404, detail=f"no such realm {realm_id!r}")
    lifecycle = [e for e in events if e.kind == EventKind.LIFECYCLE]
    state = lifecycle[-1].payload.get("event") if lifecycle else "unknown"
    # the RESOLVED configuration this run used (models, turns, budgets) — captured at launch
    config: dict[str, Any] = next(
        (e.payload["config"] for e in lifecycle if e.payload.get("config")), {}
    )
    spend: dict[str, float] = {}
    tokens: dict[str, int] = {}  # agent -> total tokens (prompt + completion)
    ledger: dict[str, float] = {}  # running score = raw re-sum of SCORE-event deltas
    verdict_board: dict[str, float] | None = None  # the arbiter board the referee RULED on
    violations: list[dict[str, Any]] = []
    outcome = None
    for e in events:
        p = e.payload
        if e.kind == EventKind.SPEND and "agent" in p:
            spend[p["agent"]] = round(spend.get(p["agent"], 0.0) + float(p.get("usd", 0)), 6)
            tokens[p["agent"]] = tokens.get(p["agent"], 0) + int(p.get("tokens_in", 0) or 0) \
                + int(p.get("tokens_out", 0) or 0)
        elif e.kind == EventKind.SCORE and "agent" in p:
            ledger[p["agent"]] = round(ledger.get(p["agent"], 0.0) + float(p.get("delta", 0)), 6)
        elif e.kind == EventKind.VIOLATION and "agent" in p:
            violations.append({"agent": p["agent"], "reason": p.get("reason", "")})
        elif e.kind == EventKind.VERDICT:
            outcome = p.get("outcome", outcome)
            sb = p.get("scoreboard")
            if isinstance(sb, dict) and sb:  # the referee's ruling carries its own scoreboard
                verdict_board = {k: round(float(v), 6) for k, v in sb.items()}
    # Once the referee has RULED, its recorded scoreboard is the score of record — not a re-sum of
    # raw SCORE events. Those two normally agree, but the re-sum can be corrupted by a duplicate
    # SCORE write (rps-rv1: a spurious second 'round R1' event inflated the ledger to 3-2 while the
    # referee's own board, outcome, and reasons all said 2-2). Physics-vs-law: the referee's verdict
    # is law, so once it exists we surface its board and flag — not hide — any divergence.
    scores = verdict_board if verdict_board is not None else ledger
    score_discrepancy = verdict_board is not None and verdict_board != ledger
    msgs = await chron.messages(realm_id)
    return {
        "realm_id": realm_id, "state": state, "outcome": outcome,
        "config": config,
        "spend": spend, "total_spend": round(sum(spend.values()), 6),
        "tokens": tokens, "total_tokens": sum(tokens.values()),
        "scores": scores, "score_ledger": ledger, "score_discrepancy": score_discrepancy,
        "violations": violations,
        "messages": len(msgs), "events": len(events),
    }


def _allowed_hosts() -> list[str]:
    """Host headers this control plane will answer to.

    `testserver` is Starlette's TestClient host. Set AGENTREALM_ALLOWED_HOSTS to a comma-separated
    list to serve on a real hostname; "*" disables the check, which is only safe on a host nobody
    else can reach.
    """
    configured = os.environ.get("AGENTREALM_ALLOWED_HOSTS", "").strip()
    if configured:
        return [h.strip() for h in configured.split(",") if h.strip()]
    return ["localhost", "127.0.0.1", "[::1]", "testserver"]


def create_app(
    *,
    chron: Chronicle | None = None,
    manager: RealmManager | None = None,
    scribe_backend: LLMBackend | None = None,
    scribe_store: PackageStore | None = None,
    scribe_root: Path | None = None,
    auth_token: str | None = None,
) -> FastAPI:
    """Build the app. Prod: pass nothing — the lifespan builds the Platform, and the API token is
    loaded (or generated) from ~/.agentrealm/api-token. Tests: inject a chronicle (+ optional
    manager) to exercise the read/control endpoints without the stack, and a scribe backend/store/
    root to exercise the guided-authoring endpoints with no model calls.

    `auth_token` gates every /api/* route. An INJECTED app defaults to no token, because a test
    asserting an endpoint's behaviour should not have to re-assert the auth wrapper each time —
    `tests/test_api_auth.py` builds an app WITH a token and covers that separately."""
    injected = chron is not None
    token = auth_token if auth_token is not None else (None if injected else load_or_create_token())

    @asynccontextmanager
    async def lifespan(a: FastAPI) -> AsyncIterator[None]:
        if injected:
            a.state.chron = chron
            a.state.manager = manager
            a.state.platform = None
            yield
        else:
            platform = await build_platform()
            await reconcile_orphans(platform.chronicle)  # fix realms left "running" by a restart
            # ...and destroy the CONTAINERS that restart left behind. reconcile_orphans only made
            # the DATABASE honest: it marked the realm "interrupted" while its agents kept running,
            # holding live model keys, with nobody watching. Nothing is active at startup, so this
            # sweeps every leftover.
            reaped = platform.forge.reap_orphans(active=())
            if reaped:
                log.warning("reaped %d orphaned agent container(s): %s", len(reaped),
                            ", ".join(sorted(reaped)))
            a.state.platform = platform
            a.state.chron = platform.chronicle
            a.state.manager = RealmManager(platform)
            try:
                yield
            finally:
                await a.state.manager.shutdown()
                # a clean shutdown concludes each realm, which tears its agents down — but a realm
                # that fails to conclude must not leave them running either.
                with contextlib.suppress(Exception):
                    platform.forge.reap_orphans(active=())
                await platform.close()

    app = FastAPI(title="AgentRealm", lifespan=lifespan)

    # This origin has no authentication (see #105) and can start realms, spend money, and read
    # every transcript, private note and revealed submission. It binds to loopback by default, but
    # loopback alone stops neither of the two ways a web page reaches it:
    #
    #   DNS rebinding — attacker.example resolves to 127.0.0.1, so the browser connects locally
    #     while believing it is same-origin. The Host header still says attacker.example, so an
    #     allowlist rejects it.
    #   Cross-site form POST — /stop and /rerun take no body, so a plain HTML form on any page
    #     reaches them with no preflight. Requests from another origin are refused below.
    app.add_middleware(TrustedHostMiddleware, allowed_hosts=_allowed_hosts())

    @app.middleware("http")
    async def _require_token(request: Request, call_next: Any) -> Response:
        """Gate /api/* on the local token, and let `/?token=…` exchange it for a cookie.

        The exchange is what makes this usable from a browser without a login form: `arealm serve`
        prints the URL with the token in it, opening it stores an HttpOnly SameSite=Strict cookie,
        and the console then works normally. Scripts send `Authorization: Bearer <token>`."""
        if token is None:
            return await call_next(request)  # type: ignore[no-any-return]

        path = request.url.path
        supplied = presented_token(
            header=request.headers.get("authorization"),
            cookie=request.cookies.get(COOKIE_NAME),
            query=request.query_params.get(QUERY_PARAM),
        )
        if not is_public_path(path) and not token_matches(token, supplied):
            return JSONResponse(
                {"detail": "missing or invalid API token — see the URL printed by `arealm serve`"},
                status_code=401,
            )
        response: Response = await call_next(request)
        # A correct token on the console page becomes a cookie, so it need not stay in the URL.
        if path == "/" and token_matches(token, request.query_params.get(QUERY_PARAM)):
            response.set_cookie(
                COOKIE_NAME, token, httponly=True, samesite="strict", path="/",
                max_age=60 * 60 * 24 * 30,
            )
        return response

    @app.middleware("http")
    async def _block_cross_site_writes(request: Request, call_next: Any) -> Response:
        if request.method not in ("GET", "HEAD", "OPTIONS"):
            origin = request.headers.get("origin")
            # A same-origin fetch sends no Origin (or its own); a cross-site form POST sends the
            # attacker's. Sec-Fetch-Site is checked too where the browser provides it.
            if (origin and origin != str(request.base_url).rstrip("/")) or \
                    request.headers.get("sec-fetch-site") in ("cross-site", "same-site"):
                return JSONResponse({"detail": "cross-site request refused"}, status_code=403)
        response: Response = await call_next(request)
        return response

    def get_chron() -> Chronicle:
        return app.state.chron  # type: ignore[no-any-return]

    def get_manager() -> RealmManager:
        return app.state.manager  # type: ignore[no-any-return]

    def _static(name: str) -> str:
        """Read a UI asset from the static dir. Read fresh each call (the files are tiny) so a UI
        edit shows up without a server restart. Returns "" if absent."""
        f = STATIC_DIR / name
        return f.read_text() if f.is_file() else ""

    # The UI ships as a few unversioned files that change often, so tell browsers never to cache
    # them — otherwise a reload keeps serving stale app.js and fixes appear not to land.
    _NO_CACHE = {"Cache-Control": "no-store, max-age=0"}

    @app.get("/", response_class=HTMLResponse)
    async def dashboard() -> Response:
        # No fallback UI. There used to be a second, older console embedded in Python that served
        # whenever index.html was missing — but index.html ships with the package, so the fallback
        # never ran and quietly rotted. A missing asset is now a visible failure, not a different
        # and stale interface.
        html = _static("index.html")
        if not html:
            raise HTTPException(status_code=500, detail=f"UI assets missing from {STATIC_DIR}")
        return Response(html, media_type="text/html", headers=_NO_CACHE)

